import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { parseProof, runProof } from '../fixtures/lib/checks.mjs';
import { checkoutNewBranch, commitAll, git, initRepo, mergeNoFf, writeChanges } from '../fixtures/lib/git.mjs';
import { dossierOf } from './classify.ts';
import { ingest } from './record.ts';
import { proveRoutine, routineParts } from './proofs.ts';

const ANA = { name: 'Ana Lima', email: 'ana@example.com' };

function toy(files: Readonly<Record<string, string>>): string {
  const workspace = fs.mkdtempSync(path.join(os.tmpdir(), 'nmem-proof-'));
  const repoDir = path.join(workspace, 'repo');
  initRepo(repoDir);
  writeChanges(repoDir, {
    'README.md': '# toy\n\nToy prints a greeting.\n',
    'package.json': '{ "name": "toy", "version": "1.0.0" }\n',
    'package-lock.json': '{ "packages": { "": { "name": "toy", "version": "1.0.0" } } }\n',
    'src/allow.ts': 'export const allowance = 1;\n',
    'src/quotes.ts': "export const label = 'open';\n",
  });
  commitAll(repoDir, { ...ANA, date: '2024-01-01T10:00:00Z' }, 'Initial commit');
  checkoutNewBranch(repoDir, 'topic-1');
  writeChanges(repoDir, files);
  const sha = commitAll(repoDir, { ...ANA, date: '2024-01-02T10:00:00Z' }, 'Refresh the list and restyle') as string;
  git(repoDir, ['checkout', '--quiet', 'main']);
  const merge = mergeNoFf(repoDir, 'topic-1', { ...ANA, date: '2024-01-02T11:00:00Z' }, 'Merge pull request #1') as string;
  const github = {
    repo: { owner: 'acme', name: 'toy' },
    users: [{ login: 'ana', name: ANA.name, type: 'User' }],
    pulls: [{ number: 1, title: 'Refresh the list and restyle', body: 'Refreshes the list.', author: 'ana', mergeCommitSha: merge, commits: [{ sha, authorLogin: 'ana' }], comments: [], reviews: [] }],
    issues: [],
    discussions: [],
  };
  fs.writeFileSync(path.join(workspace, 'github.json'), JSON.stringify(github));
  return workspace;
}

const LOCK = `{
  "packages": {
    "": { "name": "toy", "version": "1.0.0" },
    "node_modules/left-pad": { "version": "1.0.0" }
  }
}
`;

const GENERATED = `// Generated by a tool. Do not edit.
export type Account = { id: string };
`;

test('a lockfile refresh, a restyle, and an unused generated file are routine parts, and the dossier shows the code', () => {
  const record = ingest(toy({
    'package-lock.json': LOCK,
    'src/allow.ts': 'export const allowance = 2;\n',
    'src/quotes.ts': 'export const label = "open";\n',
    'src/generated/partner-client.ts': GENERATED,
  }));
  const change = record.changes.find((item) => item.id === 'pr#1');
  assert.ok(change);
  assert.equal(proveRoutine(record.repoDir, change), null);
  const from = change.before.slice(0, 7);
  const to = change.after.slice(0, 7);
  const parts = routineParts(record.repoDir, change);
  assert.deepEqual(parts.map((part) => [part.files, part.proof]), [
    [['package-lock.json'], `lockfile ${from}..${to}`],
    [['src/generated/partner-client.ts'], `grep ${to} partner-client`],
    [['src/quotes.ts'], `restyle ${from}..${to}:src/quotes.ts`],
  ]);
  assert.deepEqual(parts.map((part) => part.name.eng), ['lockfile refresh', 'generated file', 'restyle']);
  assert.equal(runProof(record.repoDir, parseProof(parts[0]!.proof)).text, 'package.json unchanged; versions changed: none; removed: none; added: 1, used by any other file: none, with an install script: none');
  assert.equal(runProof(record.repoDir, parseProof(parts[1]!.proof)).text, '(no matches)');
  assert.equal(runProof(record.repoDir, parseProof(parts[2]!.proof)).text, 'only quote marks changed');
  const text = dossierOf(record, change, []).text;
  const code = text.split('Code, one diff per commit and file')[1] ?? '';
  assert.match(text, /Proven routine, not shown: package-lock\.json \(lockfile refresh\), src\/generated\/partner-client\.ts \(generated file\), src\/quotes\.ts \(restyle\)/);
  assert.equal(code.includes('package-lock.json'), false);
  assert.equal(code.includes('partner-client.ts'), false);
  assert.equal(code.includes('src/quotes.ts'), false);
  assert.match(code, /src\/allow\.ts/);
  assert.match(code, /\+export const allowance = 2;/);
});

test('a used addition, an install script, a named generated file, and a code edit are not routine parts', () => {
  const usedRecord = ingest(toy({
    'package-lock.json': LOCK,
    'src/allow.ts': 'export const pad = "left-pad";\n',
  }));
  const usedChange = usedRecord.changes.find((item) => item.id === 'pr#1');
  assert.ok(usedChange);
  assert.equal(routineParts(usedRecord.repoDir, usedChange).some((part) => part.files.includes('package-lock.json')), false);

  const scripted = `{
  "packages": {
    "": { "name": "toy", "version": "1.0.0" },
    "node_modules/left-pad": { "version": "1.0.0", "hasInstallScript": true }
  }
}
`;
  const scriptRecord = ingest(toy({ 'package-lock.json': scripted }));
  const scriptChange = scriptRecord.changes.find((item) => item.id === 'pr#1');
  assert.ok(scriptChange);
  assert.deepEqual(routineParts(scriptRecord.repoDir, scriptChange), []);

  const named = ingest(toy({
    'src/generated/partner-client.ts': GENERATED,
    'src/allow.ts': 'import type { Account } from "./generated/partner-client";\nexport const allowance = 2;\n',
  }));
  const namedChange = named.changes.find((item) => item.id === 'pr#1');
  assert.ok(namedChange);
  assert.equal(routineParts(named.repoDir, namedChange).some((part) => part.proof.startsWith('grep ')), false);

  const edited = ingest(toy({ 'src/quotes.ts': 'export const label = "closed";\n' }));
  const editedChange = edited.changes.find((item) => item.id === 'pr#1');
  assert.ok(editedChange);
  assert.deepEqual(routineParts(edited.repoDir, editedChange), []);
});
